'use strict';
/* The pg adapter, against a real PostgreSQL.
 *
 * `e2e-pgsql.js` fuzzes the rewriter with no database. This is the other half:
 * the things that are only true when a server is on the other end — what type a
 * COUNT comes back as, whether `changes` counts rows, whether a transaction
 * actually pins a connection, and whether an at-most-once gate stays at most
 * once when two callers really do interleave.
 *
 * Runs in the `postgres prepare sweep` CI job, which already has a server:
 *   node scripts/pg-adapter-check.js "postgres://…"
 *
 * It is NOT part of `npm test`, because a check that silently skips when no
 * database is present is a check nobody notices has stopped running.
 */
const pg = require('../src/db/pg');

const URL = process.argv[2] || process.env.DATABASE_URL;
if (!URL) {
  console.error('usage: node scripts/pg-adapter-check.js <postgres-url>');
  process.exit(2);
}

let pass = 0;
let fail = 0;
function chk(name, cond, detail) {
  // Same rule as e2e-lib: a Promise is truthy, so an unawaited assertion would
  // pass unconditionally. That is the exact bug class this whole port is about.
  if (cond && typeof cond.then === 'function') {
    console.error(`FAIL  ${name} — assertion is a thenable; add the missing await`);
    fail++; return;
  }
  if (cond) { pass++; console.log(`PASS  ${name}`); }
  else { fail++; console.error(`FAIL  ${name}${detail ? ` — ${detail}` : ''}`); }
}

(async () => {
  pg.connect(URL, { max: 5 });

  await pg.run('DROP TABLE IF EXISTS adapter_check');
  await pg.run(`CREATE TABLE adapter_check (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text UNIQUE,
    claimed_at bigint,
    ratio numeric,
    payload text)`);

  // ── 1. the types. This is the seed-guard bug ──────────────────────────────
  // node-postgres returns int8 and numeric as STRINGS by default. Every
  // `COUNT(*) === 0` guard in db.js then reads '0' === 0 → false, and a fresh
  // install seeds no organisation, no admin, no components, no alert rule —
  // silently, with a 200 on every request.
  const c = await pg.get('SELECT COUNT(*) AS n FROM adapter_check');
  chk('COUNT(*) comes back as a number, not a string', typeof c.n === 'number', typeof c.n);
  chk('…and compares equal to 0, which is what every seed guard asks', c.n === 0, JSON.stringify(c.n));

  await pg.run('INSERT INTO adapter_check (name, ratio) VALUES (?, ?)', 'a', 0.5);
  const r = await pg.get('SELECT ratio, id FROM adapter_check WHERE name = ?', 'a');
  chk('numeric comes back as a number', typeof r.ratio === 'number', typeof r.ratio);
  chk('a bigint identity comes back as a number', typeof r.id === 'number', typeof r.id);
  chk('arithmetic on a COUNT stays arithmetic',
    (await pg.get('SELECT COUNT(*) AS n FROM adapter_check')).n + 1 === 2);

  // ── 2. `changes` means rows affected ──────────────────────────────────────
  // Every Phase 2 at-most-once gate decides on this number. If it ever means
  // anything else, all forty of them stop gating and nothing throws.
  const up = await pg.run('UPDATE adapter_check SET payload = ? WHERE name = ?', 'x', 'a');
  chk('run() reports one change for one updated row', up.changes === 1, String(up.changes));
  const none = await pg.run('UPDATE adapter_check SET payload = ? WHERE name = ?', 'x', 'nobody');
  chk('…and zero when the WHERE matches nothing', none.changes === 0, String(none.changes));

  // ── 3. the at-most-once gate, with real interleaving ──────────────────────
  // The whole point of Phase 2. Ten callers race to claim one row; the database
  // must hand it to exactly one of them.
  await pg.run('INSERT INTO adapter_check (name) VALUES (?)', 'claimable');
  const claims = await Promise.all(Array.from({ length: 10 }, (_, i) => pg.run(
    'UPDATE adapter_check SET claimed_at = ? WHERE name = ? AND claimed_at IS NULL', 1000 + i, 'claimable')));
  const winners = claims.filter((x) => x.changes === 1).length;
  chk('ten parallel claims of one row: exactly one wins',
    winners === 1, `${winners} winners`);

  // ── 4. the transaction really pins a connection ───────────────────────────
  // Risk #3 in the plan: with a pool and no pinning, BEGIN goes to one
  // connection and the writes to others. Every statement succeeds, nothing
  // throws, and the ROLLBACK covers nothing at all. Proven by looking from
  // outside the transaction while it is open — a pooled reader must NOT see the
  // uncommitted row.
  let seenFromOutside = null;
  await pg.withTx(async () => {
    await pg.run('INSERT INTO adapter_check (name) VALUES (?)', 'pinned');
    const inside = await pg.get('SELECT name FROM adapter_check WHERE name = ?', 'pinned');
    chk('a read inside the transaction sees its own uncommitted write', !!inside);
    // A second pool client, deliberately not the pinned one.
    const pool = pg.connect(URL);
    const other = await pool.connect();
    try {
      const res = await other.query("SELECT name FROM adapter_check WHERE name = 'pinned'");
      seenFromOutside = res.rows.length;
    } finally { other.release(); }
  });
  chk('…and a different pool connection does NOT — so BEGIN pinned a client',
    seenFromOutside === 0, `saw ${seenFromOutside} row(s)`);
  chk('…and after COMMIT everyone sees it',
    !!(await pg.get('SELECT name FROM adapter_check WHERE name = ?', 'pinned')));

  // ── 5. rollback actually rolls back ───────────────────────────────────────
  let threw = null;
  try {
    await pg.withTx(async () => {
      await pg.run('INSERT INTO adapter_check (name) VALUES (?)', 'doomed');
      throw new Error('deliberate');
    });
  } catch (e) { threw = e; }
  chk('a throw inside withTx propagates', threw && threw.message === 'deliberate');
  chk('…and the write is gone',
    !(await pg.get('SELECT name FROM adapter_check WHERE name = ?', 'doomed')));

  // A nested withTx must JOIN the open transaction, not open a second one: a
  // second pool client would deadlock against the first's row locks, and the
  // inner COMMIT would publish half the outer transaction's work.
  await pg.withTx(async () => {
    await pg.run('INSERT INTO adapter_check (name) VALUES (?)', 'outer');
    await pg.withTx(async () => { await pg.run('INSERT INTO adapter_check (name) VALUES (?)', 'inner'); });
    chk('a nested withTx joins the open transaction rather than opening a second',
      !!(await pg.get('SELECT name FROM adapter_check WHERE name = ?', 'inner')));
  });

  // ── 6. a unique violation is recognisable ─────────────────────────────────
  // routes/vendors.js answers 409 on String(e.message).includes('UNIQUE'), which
  // is better-sqlite3's wording. Under pg that becomes an unhandled 500 unless
  // the adapter tags it.
  let dup = null;
  try { await pg.run('INSERT INTO adapter_check (name) VALUES (?)', 'a'); } catch (e) { dup = e; }
  chk('a duplicate raises', dup !== null);
  chk('…tagged as a unique violation', dup && dup.isUniqueViolation === true);
  chk('…and still says UNIQUE, so an unconverted handler still answers 409',
    dup && /UNIQUE/.test(dup.message), dup && dup.message);

  // ── 7. named parameters, the one statement that uses them ─────────────────
  const named = await pg.run(
    'INSERT INTO adapter_check (name, claimed_at, payload) VALUES (@n, @ts, @n)',
    { n: 'named-row', ts: 42 });
  chk('a named statement inserts', named.changes === 1);
  const nr = await pg.get('SELECT claimed_at, payload FROM adapter_check WHERE name = ?', 'named-row');
  chk('…and a repeated @name binds the same value to both positions',
    nr && nr.payload === 'named-row' && nr.claimed_at === 42, JSON.stringify(nr));

  // ── 8. a ? inside a literal survives the round trip ───────────────────────
  await pg.run('INSERT INTO adapter_check (name, payload) VALUES (?, ?)', 'q', 'what?');
  const lit = await pg.get("SELECT name FROM adapter_check WHERE payload LIKE '%?%' AND name = ?", 'q');
  chk('a ? inside a string literal is still data at the server', !!lit);

  /* ── 9. the SHIM used to be re-tested here, and no longer is ──────────────
   *
   * This section duplicated e2e-shim.js — insert()/RETURNING, `changes`, the
   * lastInsertRowid refusal, the strict thenable, withTx commit and rollback —
   * because e2e-shim.js ran against SQLite and something had to make the same
   * claims on the engine that actually serves. e2e-shim.js runs on Postgres now
   * (D6), in `npm test`, on every push. Repeating it here would be a second CI
   * job asserting the same things, which is how one of them stops being read.
   *
   * What stays above is what only this file can say: it talks to `src/db/pg.js`
   * DIRECTLY, below the shim, so the type parsers, the error tagging and the
   * placeholder round trip are measured without the shim's semantics in the way.
   */

  await pg.run('DROP TABLE adapter_check');
  await pg.close();

  console.log(`\n${pass}/${pass + fail} checks passed`);
  process.exit(fail ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
